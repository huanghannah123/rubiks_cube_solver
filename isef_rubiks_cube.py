def style_axis(ax, xlabel, ylabel, distances):
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_xticks(distances)
    ax.grid(True, color="#e6e5e0", linewidth=0.8)
